-- ไฟล์นี้สร้างตาราง ข้อจำกัด ดัชนี และ RLS ของ ThaiFood ในฐานข้อมูล/schema ของแอป
-- รันซ้ำได้ด้วย IF NOT EXISTS; transaction จะ commit เมื่อทุกคำสั่งสำเร็จ
BEGIN;

-- ข้อมูลอ้างอิงจังหวัด: ชื่อไทยไม่ซ้ำ และต้องมีชื่อ/ภูมิภาคที่ไม่ว่าง
CREATE TABLE IF NOT EXISTS provinces (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_th text NOT NULL UNIQUE CHECK (length(btrim(name_th)) > 0),
    region text NOT NULL CHECK (length(btrim(region)) > 0)
);

-- ข้อมูลอ้างอิงประเภทอาหาร: ใช้ ID เชื่อมกับร้านและเก็บชื่อไทยที่ไม่ซ้ำ
CREATE TABLE IF NOT EXISTS categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_th text NOT NULL UNIQUE CHECK (length(btrim(name_th)) > 0)
);

-- ข้อมูลร้าน: อ้างอิงจังหวัดและประเภทอาหาร พร้อมจำกัดความยาวข้อความ/ช่วงพิกัด
-- พิกัดต้องมีทั้ง latitude และ longitude หรือเป็น NULL ทั้งคู่; source ใช้กันข้อมูลนำเข้าซ้ำ
CREATE TABLE IF NOT EXISTS restaurants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 200),
    province_id bigint NOT NULL REFERENCES provinces(id) ON DELETE RESTRICT,
    category_id bigint NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    address text NOT NULL CHECK (char_length(btrim(address)) BETWEEN 1 AND 1000),
    description text NOT NULL CHECK (char_length(btrim(description)) BETWEEN 1 AND 5000),
    latitude double precision CHECK (latitude BETWEEN -90 AND 90),
    longitude double precision CHECK (longitude BETWEEN -180 AND 180),
    image_url text,
    source_name text,
    source_url text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((latitude IS NULL) = (longitude IS NULL))
);

-- ดัชนีช่วยกรองร้านและป้องกันการนำเข้ารายการเดิมซ้ำจากคู่ source_name/source_url
CREATE INDEX IF NOT EXISTS restaurants_province_category_idx ON restaurants(province_id,category_id);
CREATE INDEX IF NOT EXISTS restaurants_category_idx ON restaurants(category_id);
CREATE UNIQUE INDEX IF NOT EXISTS restaurants_source_idx ON restaurants(source_name,source_url) WHERE source_name IS NOT NULL AND source_url IS NOT NULL;

-- สมาชิกเก็บเฉพาะ password hash และอนุญาต role แค่ member/admin โดยค่าเริ่มต้นเป็น member
CREATE TABLE IF NOT EXISTS members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL CHECK (char_length(btrim(email)) BETWEEN 3 AND 254),
    password_hash text NOT NULL CHECK (length(password_hash) > 0),
    display_name text NOT NULL CHECK (char_length(btrim(display_name)) BETWEEN 1 AND 100),
    role text NOT NULL DEFAULT 'member' CHECK (role IN ('member','admin')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
-- อีเมลที่ต่างกันเฉพาะตัวพิมพ์เล็กใหญ่ถือว่าเป็นบัญชีเดียวกัน
CREATE UNIQUE INDEX IF NOT EXISTS members_email_ci_idx ON members(lower(email));

-- รีวิวจำกัดหนึ่งสมาชิกต่อหนึ่งร้าน คะแนนจำนวนเต็ม 1–5 และลบตามเมื่อร้านหรือสมาชิกถูกลบ
CREATE TABLE IF NOT EXISTS reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id bigint NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    member_id bigint NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    text text NOT NULL CHECK (char_length(btrim(text)) BETWEEN 10 AND 5000),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (member_id,restaurant_id)
);
CREATE INDEX IF NOT EXISTS reviews_restaurant_idx ON reviews(restaurant_id);

-- รายการโปรดใช้ primary key แบบคู่สมาชิก/ร้าน ป้องกันบันทึกร้านเดิมซ้ำและลบตามข้อมูลแม่
CREATE TABLE IF NOT EXISTS favorites (
    member_id bigint NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    restaurant_id bigint NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (member_id,restaurant_id)
);
CREATE INDEX IF NOT EXISTS favorites_restaurant_idx ON favorites(restaurant_id);

-- เปิด RLS ทุกตาราง โดยให้ API ฝั่ง Go ที่เชื่อมในฐานะ database owner เป็นทางเข้าถึงข้อมูล
ALTER TABLE provinces ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE restaurants ENABLE ROW LEVEL SECURITY;
ALTER TABLE members ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE favorites ENABLE ROW LEVEL SECURITY;

-- ไม่สร้าง policy อนุญาต client โดยตรง และถอนสิทธิ์ anon/authenticated ทั้งตารางและ sequence
-- ตรวจว่า role มีอยู่ก่อน เพื่อให้ schema เดียวกันรันบน PostgreSQL ท้องถิ่นที่ไม่มี role ของ Supabase ได้
DO $block$
DECLARE api_role text;
BEGIN
    FOREACH api_role IN ARRAY ARRAY['anon','authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=api_role) THEN
            EXECUTE format('REVOKE ALL ON TABLE provinces,categories,restaurants,members,reviews,favorites FROM %I', api_role);
            EXECUTE format('REVOKE ALL ON SEQUENCE provinces_id_seq,categories_id_seq,restaurants_id_seq,members_id_seq,reviews_id_seq FROM %I', api_role);
        END IF;
    END LOOP;
END
$block$;

-- ยืนยันการเปลี่ยนแปลงทั้งหมดใน transaction นี้
COMMIT;
